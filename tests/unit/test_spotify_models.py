from datetime import UTC, datetime

import pytest
from pydantic import ValidationError

from kexp2spotify.domain import ManagedPlaylist, Show, SongQueueItem
from kexp2spotify.spotify_playlists import playlist_description, playlist_name


def test_spotify_domain_rejects_empty_identity_and_duplicate_tracks() -> None:
    with pytest.raises(ValidationError):
        Show(id="", name="Show")
    with pytest.raises(ValidationError):
        ManagedPlaylist(
            show_id="show",
            provider_playlist_id="playlist",
            name="KEXP - Show",
            track_uris=["spotify:track:1", "spotify:track:1"],
        )


def test_description_is_timezone_aware_and_exact() -> None:
    value = playlist_description(datetime(2026, 10, 10, 22, 30, tzinfo=UTC), "Europe/Madrid")
    assert (
        value
        == "Last Updated at 00:30 at 11-10-2026 (Europe/Madrid) + Autogenerated by https://github.com/JorgeRuizDev/kexp2spotify"
    )


def test_queue_requires_timezone_aware_timestamp() -> None:
    with pytest.raises(ValidationError):
        SongQueueItem(show_id="show", track_id="track", queued_at=datetime(2026, 1, 1))


def test_playlist_name_normalizes_whitespace() -> None:
    assert playlist_name("  Morning   Show ") == "KEXP - Morning Show"
